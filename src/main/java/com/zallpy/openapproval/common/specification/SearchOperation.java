package com.zallpy.openapproval.common.specification;

/**
 * Supported search operations.
 *
 * @author Zallpy
 * @since 1.0.0
 */
public enum SearchOperation {

    EQUAL,

    NOT_EQUAL,

    GREATER_THAN,

    GREATER_THAN_OR_EQUAL,

    LESS_THAN,

    LESS_THAN_OR_EQUAL,

    LIKE,

    CONTAINS,

    STARTS_WITH,

    ENDS_WITH,

    IN,

    NOT_IN,

    BETWEEN,

    IS_NULL,

    IS_NOT_NULL

}